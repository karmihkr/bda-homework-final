# -*- coding: utf-8 -*-
"""Эталонные ответы к заданиям сквозного проекта.

Считает по сгенерированному комплекту то, что обучающийся должен получить на
каждом этапе. Предназначен преподавателю: без него невозможно применить
критерий 3 «корректность обработки данных» и блокирующий критерий 5
«воспроизводимость» — не с чем сравнивать.

    python reference_answers.py ./out [--out reference_answers.md]

Этапы 3 и 4 (распределённая обработка, конвейер) проверяются здесь только по
результату: совпадение агрегатов с эталоном. Способ вычисления — предмет
защиты, а не автоматической сверки.
"""
import argparse
import glob
import json
import os
import numpy as np
import pandas as pd

OUT = []


def say(s=""):
    OUT.append(s)
    print(s)


def h(t):
    say()
    say(t)
    say("-" * len(t))


def load_cdr(paths, cols=None, skip_broken=True):
    frames, broken = [], []
    for p in paths:
        f = os.path.join(p, "cdr.csv") if os.path.isdir(p) else p
        try:
            frames.append(pd.read_csv(f, usecols=cols, low_memory=False))
        except Exception:
            broken.append(f)
    df = pd.concat(frames, ignore_index=True) if frames else pd.DataFrame()
    return (df, broken) if skip_broken else df


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("root")
    ap.add_argument("--out", default="reference_answers.md")
    a = ap.parse_args()
    root, raw, ref = a.root, os.path.join(a.root, "raw"), os.path.join(a.root, "reference")

    pas = json.load(open(os.path.join(ref, "passport.json"), encoding="utf-8"))
    agg = pd.read_csv(os.path.join(ref, "aggregates_daily.csv"))
    led = pd.read_csv(os.path.join(ref, "defect_ledger.csv"))
    churn = pd.read_csv(os.path.join(ref, "churn_truth.csv"))
    scd = pd.read_csv(os.path.join(ref, "subscribers_scd2_truth.csv"))
    tar = pd.read_csv(os.path.join(raw, "dictionaries", "tariffs.csv"))
    parts = sorted(glob.glob(os.path.join(raw, "cdr", "dt=*")))
    start = np.datetime64(pas["period_start"])

    say(f"# Эталонные ответы к заданиям сквозного проекта")
    say()
    say(f"Комплект: уровень **{pas['level']}**, начальное состояние **{pas['seed']}**, "
        f"генератор **{pas['generator_version']}**.")
    say(f"Период: {pas['period_start']}, {pas['period_days']} суток. "
        f"Записей о соединениях: {pas['rows']['cdr']:,}.".replace(",", " "))
    say()
    say("> Документ содержит правильные ответы. Обучающимся не выдаётся.")

    # ───────────────────────────────────────────────────────────── этап 1
    h("Этап 1. Профилирование и постановка задачи")
    say(f"**Суточных выгрузок в основной поставке:** {len(parts)} "
        f"(из {pas['period_days']} суток периода).")
    miss = [str(start + np.timedelta64(d, "D")) for d in pas["missing_day_indices"]]
    say(f"**Отсутствуют в основной поставке и лежат в `late_delivery/`:** {', '.join(miss)}.")
    say(f"**Повреждённая выгрузка:** {start + np.timedelta64(pas['broken_day_index'], 'D')}. "
        f"Три симптома: часть строк со сдвигом колонок, фрагмент в кодировке cp1251, "
        f"обрыв файла на середине записи.")
    say()
    say("**Что обучающийся обязан обнаружить при профилировании** "
        "(фактические доли по всему периоду):")
    say()
    say("| Дефект | Доля, % | Записей |")
    say("|---|---|---|")
    for _, r in led.iterrows():
        say(f"| {r.description} | {r.actual_rate * 100:.3f} | {int(r.actual_count):,} |"
            .replace(",", " "))
    say()
    say(f"**Незаполненный идентификатор узла сети:** около 5 % записей — отдельно от "
        f"перечисленных дефектов, это свойство источника, а не ошибка.")
    say()
    say("**Типичные пропуски в ответах:** обучающиеся находят пропуски и дубликаты, но "
        "упускают смешанные форматы даты (2 %) и несогласованные написания "
        "справочных значений (4 %), поскольку те не видны в сводной статистике.")

    # ───────────────────────────────────────────────────────────── этап 2
    h("Этап 2. Хранение, партиционирование, витрина")
    dfp, broken = load_cdr(parts[:: max(1, len(parts) // 10)][:10],
                           ["region_id", "tariff_id", "service_type", "node_id"])
    say(f"**Распределение по регионам** (доля крупнейших, выборка {len(dfp):,} записей):"
        .replace(",", " "))
    sh = dfp.region_id.value_counts(normalize=True)
    say(f"первые два региона — {sh.iloc[:2].sum() * 100:.1f} %, "
        f"первые десять — {sh.iloc[:10].sum() * 100:.1f} %.")
    say()
    say("**Правильный вывод по ключу партиционирования:** дата соединения — основной "
        "ключ (равномерна и совпадает с шаблоном запросов); регион как второй уровень "
        "допустим, но порождает перекос разделов, поскольку два региона дают треть "
        "объёма. Филиал в качестве ключа хуже: филиалов десять, разделы получаются "
        "крупными и отсечение почти не работает.")
    say()
    card = {c: int(dfp[c].nunique()) for c in ("service_type", "tariff_id", "node_id")}
    say(f"**Кардинальность полей:** {card}. Колоночный формат даёт наибольший выигрыш "
        f"на `service_type` и `tariff_id` (словарное кодирование), наименьший — на "
        f"`node_id` и идентификаторе записи.")
    say()
    say(f"**Справочник тарифных планов:** {len(tar)} строк. Это условие задания о "
        f"широковещательном соединении: справочник заведомо помещается в память "
        f"каждого исполнителя.")
    say()
    ch = (scd.groupby("subscriber_key").size() > 1)
    say(f"**История изменений справочника абонентов:** {ch.mean() * 100:.1f} % абонентов "
        f"имеют более одной версии. Снимки выданы на {len([f for f in os.listdir(os.path.join(raw, 'dictionaries')) if f.startswith('subscribers_snapshot')])} дат; "
        f"восстановленная история должна совпасть с `reference/subscribers_scd2_truth.csv`.")
    say()
    say("**Частая ошибка:** соединение фактов с актуальной версией справочника вместо "
        "версии, действовавшей на дату соединения. Признак ошибки — тарифный план в "
        "витрине не совпадает с `tariff_id` в записи о соединении у тех абонентов, "
        "кто менял тариф.")

    # ───────────────────────────────────────────────────────────── этап 3
    h("Этап 3. Распределённая обработка и перекос")
    sp = pas["skew_profile"]
    say(f"**Профиль перекоса, который обучающийся должен обнаружить:**")
    say()
    say(f"- верхние 0,1 % абонентов дают **{sp['top_0_1pct_subscriber_share'] * 100:.1f} %** записей;")
    say(f"- абонентов с долей свыше 1 % каждый: **{sp['subscribers_above_1pct']}**;")
    say(f"- верхний 1 % узлов сети обслуживает **{sp['top_1pct_node_share'] * 100:.1f} %** соединений;")
    say(f"- два крупнейших региона — **{sp['top_2_region_share'] * 100:.1f} %**.")
    say()
    say("**Два независимых источника перекоса при соединении.** Первый — степенное "
        "распределение активности абонентов. Второй — около 5 % записей с "
        "незаполненным `node_id`: при соединении со справочником узлов все они "
        "попадают в один раздел. Обучающийся, устранивший только первый, получит "
        "лишь частичное ускорение — это ожидаемый и оцениваемый результат.")
    say()
    say("**Правильные приёмы:** отдельная обработка записей с пустым ключом; "
        "широковещательное соединение со справочниками тарифов и географии "
        "(десятки и девяносто строк); изменение ключа для «горячих» абонентов. "
        "Кэширование промежуточного результата само по себе перекос не устраняет.")

    # ───────────────────────────────────────────────────────────── этап 4
    h("Этап 4. Конвейер, качество, запаздывание")
    lateshare = agg.late_rows.sum() / agg.cdr_rows.sum()
    say(f"**Доля записей с задержкой поступления свыше часа:** {lateshare * 100:.1f} %. "
        f"Это роуминговые записи; задержка доходит до суток.")
    say()
    say("**Следствие для суточной отчётности:** показатель за сутки D, рассчитанный "
        "утром D+1 по времени поступления, занижен примерно на эту величину. "
        "Правильное решение — считать по времени соединения с окном ожидания не менее "
        "суток и пересчитывать витрину за D при закрытии окна.")
    say()
    say(f"**Проверки качества и ожидаемые срабатывания** (доли из ведомости): "
        f"тариф вне справочника — {led.set_index('defect').loc['orphan_tariff', 'actual_rate'] * 100:.2f} %, "
        f"отрицательная длительность — {led.set_index('defect').loc['negative_duration', 'actual_rate'] * 100:.2f} %, "
        f"объём вне диапазона — {led.set_index('defect').loc['bytes_out_of_range', 'actual_rate'] * 100:.2f} %.")
    say()
    say("**Разделение на блокирующие и предупреждающие.** Останавливать конвейер должны "
        "пропуск обязательного поля и повреждение файла. Нарушение ссылочной "
        "целостности на уровне 1,5 % останавливать нельзя — иначе конвейер не отработает "
        "ни разу; такие записи выделяются в карантин.")
    say()
    say(f"**Обратное заполнение:** выгрузки за {', '.join(miss)} лежат в `late_delivery/`. "
        f"Корректный прогон должен дать те же суточные агрегаты, что и в "
        f"`reference/aggregates_daily.csv`; расхождение означает неидемпотентность шагов.")
    say()
    say("**Эталонные суточные агрегаты** (первые и последние трое суток):")
    say()
    say("| Дата | Записей | Уникальных абонентов | Трафик, ГБ | Начислено |")
    say("|---|---|---|---|---|")
    for _, r in pd.concat([agg.head(3), agg.tail(3)]).iterrows():
        say(f"| {r.date} | {int(r.cdr_rows):,} | {int(r.unique_subscribers):,} | "
            f"{r.sum_bytes / 1024 ** 3:.1f} | {r.sum_charge:,.0f} |".replace(",", " "))
    say()
    say("Агрегаты рассчитаны **до** внесения дефектов: они отражают истинное содержание "
        "источника. Совпадение с ними — критерий корректности обработки.")

    # ───────────────────────────────────────────────────────────── этап 5
    h("Этап 5. Аналитика, утечка данных, дрейф")
    say(f"**Доля абонентов, прекративших обслуживание за период:** "
        f"{churn.churned.mean() * 100:.1f} %.")
    say()
    say("**Наблюдаемые предвестники оттока** — то, на чём строится честная модель:")
    say()
    say("- спад потребления в последние недели перед уходом;")
    say("- рост числа обращений, смещение категорий к качеству услуги и начислениям;")
    say("- смещение канала обращения к телефонному.")
    say()
    say(f"**Ловушка утечки — поле `retention_contact` в обращениях.** Признак "
        f"проставляется после того, как абонент уже отнесён оператором к склонным к "
        f"оттоку, то есть является следствием прогноза, а не его основанием. "
        f"Встречается у {pas.get('leak_share_churned', '≈25')} % ушедших и менее чем у "
        f"1 % оставшихся.")
    say()
    say("**Как обучающийся обязан его обнаружить:** не по величине метрики, а по "
        "происхождению поля — момент заполнения позже момента прогноза. Ответ «признак "
        "полезен, метрика выросла» засчитывается как ошибка независимо от качества "
        "модели.")
    say()
    say(f"**Дрейф структуры потребления:** доля передачи данных растёт по ходу периода; "
        f"с {int(pas['drift_start_fraction'] * pas['period_days'])}-х суток вводится "
        f"тарифный план {pas['new_tariff']}. Модель, обученная на начале периода и "
        f"проверенная случайным разбиением, деградирует на последних месяцах — это "
        f"предмет экзаменационного задания о расхождении отложенной оценки и "
        f"эксплуатации.")
    say()
    say("**Обязательная очистка перед моделированием:** объём трафика содержит "
        "отрицательные значения (внедрённый дефект диапазона). Без их обработки "
        "логарифмирование признака даёт минус бесконечность и обучение падает. "
        "Это проверяемый признак того, что этап 4 выполнен добросовестно.")

    # ───────────────────────────────────────────────────────────── свод
    h("Сводка для оценивания")
    say("| Критерий рубрики | Чем проверяется по этому документу |")
    say("|---|---|")
    say("| 1. Постановка задачи | Полнота найденных дефектов, этап 1 |")
    say("| 2. Обоснование архитектуры | Вывод по ключу партиционирования и кардинальности, этап 2 |")
    say("| 3. Корректность обработки (блокирующий) | Совпадение суточных агрегатов с эталоном, этап 4 |")
    say("| 4. Качество модели | Обнаружение утечки и корректное разделение по времени, этап 5 |")
    say("| 5. Воспроизводимость (блокирующий) | Повтор прогона и обратное заполнение дают те же агрегаты |")
    say("| 6. Интерпретация | Объяснение перекоса и запаздывания, этапы 3 и 4 |")
    say("| 7. Защита | Способность объяснить оба источника перекоса, этап 3 |")

    with open(a.out, "w", encoding="utf-8") as f:
        f.write("\n".join(OUT) + "\n")
    print(f"\n[записано] {a.out}")


if __name__ == "__main__":
    main()
